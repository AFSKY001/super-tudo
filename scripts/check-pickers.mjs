import assert from 'node:assert/strict';
import Pickers from '../pickers.js';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const routine=fs.readFileSync(path.join(root,'routine.js'),'utf8');
const pickerSource=fs.readFileSync(path.join(root,'pickers.js'),'utf8');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
assert.match(sw,new RegExp("const CACHE_NAME='super-tudo-v"+pkg.version+"'"),'O cache do Service Worker deve acompanhar a versão do aplicativo.');
assert.match(sw,/\['\/manifest\.webmanifest',[^\]]*'\/pickers\.js'/,'O Service Worker deve armazenar o módulo de seletores para uso offline.');
assert.equal(Pickers.formatTime('06:05'),'06:05');
assert.equal(Pickers.formatTime('25:61'),'08:00');
assert.equal(Pickers.wheelIndex(Array.from({length:24},(_,i)=>i),8),8,'A roda deve iniciar na hora salva.');
assert.equal(Pickers.wheelIndex(Array.from({length:12},(_,i)=>i*5),35),7,'A roda deve iniciar no minuto salvo.');
assert.equal(Pickers.wheelIndex([0,5,10],17),0,'Valor fora da lista deve usar o primeiro item como fallback.');
assert.deepEqual(Pickers.normalizeDays([1,'2',7,0,1,-1]),[0,1,2]);
assert.match(Pickers.campoHora('08:00'),/data-picker="time"/);
assert.match(Pickers.campoHora('08:00'),/data-valor="08:00"/);
assert.match(Pickers.campoData('2026-11-23'),/data-picker="date"/);
assert.match(Pickers.campoMes('2026-11'),/data-picker="month"/);
assert.match(Pickers.campoPeriodo('2026-11-01','2026-11-07'),/data-picker="period"/);
assert.match(Pickers.campoDiaMes([1,15,31]),/data-month-day="31"/);
assert.match(Pickers.campoDatas(['2026-11-23']),/data-add-date/);
assert.equal(typeof Pickers.escolherData,'function');
assert.equal(typeof Pickers.escolherPeriodo,'function');
assert.equal(typeof Pickers.escolherMes,'function');
const days=Pickers.campoDias([1,2,5]);
assert.match(days,/aria-pressed="true"/);
assert.doesNotMatch(days,/type="checkbox"/);
assert.match(days,/data-days-preset="1,2,3,4,5"/);
assert.match(Pickers.segmentado([{v:'none',t:'Não'},{v:'required',t:'Obrigatória'}],'none'),/role="radiogroup"/);
assert.match(Pickers.interruptor('Atividade obrigatória',true),/role="switch"/);
assert.doesNotMatch(Pickers.interruptor('Atividade obrigatória',true),/type="checkbox"/);
assert.match(Pickers.campoEscolha([{v:'x',t:'Função X'}],'x'),/<template data-picker-options>/);
assert.match(index,/src="\/pickers\.js"><\/script><script src="\/routine\.js">/);
assert.match(index,/\.stp-days\{display:grid;grid-template-columns:repeat\(7,minmax\(0,1fr\)\)/);
assert.match(index,/\.stp-activity-controls\{display:grid;grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.match(index,/@media\(prefers-reduced-motion:reduce\)\{\.stp-field/);
assert.doesNotMatch(routine,/type="time"|name="rt-weekday-/);
for(const api of ['campoHora','campoData','campoMes','campoPeriodo','campoDias','campoDiaMes','campoDatas','escolherData','escolherPeriodo','escolherMes'])assert.match(pickerSource,new RegExp('function '+api+'\\('));
for(const api of ['campoHora','campoData','campoDias','campoDiaMes','campoDatas','segmentado','interruptor','campoEscolha'])assert.match(routine,new RegExp('Pickers\\.'+api));
for(const native of ['type=\\x22time\\x22','type=\\x22date\\x22','type=\\x22datetime-local\\x22','type=\\x22month\\x22','type=\\x22week\\x22'])assert.equal(index.includes(native),false);
assert.equal(index.includes('tmDaysHTML('),false);
assert.match(index,/\.stp-calendar-grid/);
assert.match(index,/\.stp-month-picker-grid/);
console.log('PASS - seletores globais de hora, data, mês, período, dias e recorrência.');
