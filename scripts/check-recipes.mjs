import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import Core from '../routine.js';
const root=process.cwd();
const routine=await fs.readFile(path.join(root,'routine.js'),'utf8');
const index=await fs.readFile(path.join(root,'index.html'),'utf8');
const pkg=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
const lock=JSON.parse(await fs.readFile(path.join(root,'package-lock.json'),'utf8'));
const sw=await fs.readFile(path.join(root,'sw.js'),'utf8');
const workflow=await fs.readFile(path.join(root,'.github/workflows/build-protected.yml'),'utf8');
assert.ok(Core.recipes,'Recipe validation core must be exported.');
const normalize=Core.recipes.normalize,validate=Core.recipes.validate;
const valid=normalize({nome:'Pão francês',ingredientes:[{nome:'Farinha de trigo',unidade:'kg',peso:'5'},{nome:'Fermento biológico',unidade:'g',peso:'50'}],pesoInicial:'5.5',pesoFinal:'4.8',rendimento:'80',unidadeRendimento:'unidades',pessoas:'2',tempoPreparo:'1h',tempoForno:'18 min',preparo:'Misturar, sovar e assar.',usaEmbalagem:'sim',tipoEmbalagem:'Saco plástico',quantidadeEmbalagem:'80',responsavel:'Padeiro',dataVersao:'23/11/2026 · v1'});
assert.equal(validate(valid),'','A complete bakery recipe must validate.');
assert.equal(valid.ingredientes.length,2);
assert.equal(validate({...valid,nome:''}),'Informe o nome da receita.');
assert.match(validate({...valid,ingredientes:[{nome:'Farinha',unidade:'',peso:'5'}]}),/unidade e o peso/);
assert.match(validate({...valid,ingredientes:[]}),/pelo menos um ingrediente/);
assert.match(validate({...valid,usaEmbalagem:'sim',tipoEmbalagem:'',quantidadeEmbalagem:''}),/tipo e a quantidade/);
assert.equal(normalize({...valid,ingredientes:Array.from({length:17},(_,i)=>({nome:'Ingrediente '+i,unidade:'g',peso:'1'}))}).ingredientes.length,14);
assert.match(routine,/FS\[recipeKey\]=FS\[recipeKey\]\|\|\{n:'Ficha técnica de receitas'/);
assert.match(routine,/if\(!LANC_KEYS\.includes\(recipeKey\)\)LANC_KEYS\.push\(recipeKey\)/);
assert.match(routine,/bridge\.rRegLanc=function\(\)[\s\S]{0,140}if\(V\.reg===recipeKey\)return recipePage\(\)/);
assert.match(routine,/S\.log\[recipeKey\]=Array\.isArray\(S\.log\[recipeKey\]\)\?S\.log\[recipeKey\]:\[\]/);
assert.match(routine,/const recipeSave=/);
assert.match(routine,/root\.stConfirm\('Excluir a ficha técnica/);
for(const field of ['pesoInicial','pesoFinal','rendimento','unidadeRendimento','pessoas','tempoPreparo','tempoForno','preparo','usaEmbalagem','tipoEmbalagem','quantidadeEmbalagem','responsavel','dataVersao'])assert.ok(routine.includes(field),'Missing recipe field: '+field);
assert.match(index,/set rRegLanc\(value\)\{rRegLanc=value\}/);
assert.match(index,/get REG_MENU_ICON_PATHS\(\)\{return REG_MENU_ICON_PATHS\}/);
assert.equal(pkg.version,'3.74.51');assert.equal(lock.version,'3.74.51');assert.equal(lock.packages?.['']?.version,'3.74.51');
assert.match(index,/const APP_VERSION='3\.74\.51'/);assert.match(sw,/super-tudo-v3\.74\.51/);
assert.match(workflow,/run: npm run check:recipes/);
console.log('PASS - ficha técnica de receitas: validação, campos, botão +, edição, exclusão e integração com Lançamentos.');
